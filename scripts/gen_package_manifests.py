#!/usr/bin/env python3
"""
Generate the package-manager manifests for a release.

A winget, Scoop or Homebrew entry is only valid with the *real* SHA-256 of the
artifact it points at, so these files cannot be written by hand in advance: they
are produced from the release archives as the last step of a build. This script
is that step, and the reason `packaging/` contains committed output rather than
templates — the committed files are the ones generated for v1.0.0, and re-running
this on a fresh release overwrites them with that release's hashes.

    # after `make` and `scripts/build_windows.sh`:
    python3 scripts/gen_package_manifests.py --version 1.0.0 \
        --exe dist/tessera.exe \
        --windows-zip tessera-windows-x86_64.zip \
        --linux-tar tessera-linux-x86_64.tar.gz \
        --macos-tar tessera-macos-arm64.tar.gz

    # or, with no archives present, generate from the .exe alone:
    python3 scripts/gen_package_manifests.py --version 1.0.0 --exe dist/tessera.exe

Exit status is 0 on success. Missing archives are reported and any manifest that
needs them is skipped rather than written with a guessed hash.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from textwrap import dedent

DEFAULT_REPO = "rkohnmn/tessera"
DEFAULT_TAG_PREFIX = "v"


def sha256_of(path: str) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest().upper()


def write(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"  wrote {path}")


def winget_version_manifest(version: str, repo: str) -> str:
    return dedent(f"""\
        # yaml-language-server: $schema=https://aka.ms/winget-manifest.version.1.6.0.schema.json
        # Generated by scripts/gen_package_manifests.py — do not edit by hand.
        PackageIdentifier: Tessera.Tessera
        PackageVersion: {version}
        DefaultLocale: en-US
        ManifestType: version
        ManifestVersion: 1.6.0
        """)


def winget_locale_manifest(version: str, repo: str) -> str:
    return dedent(f"""\
        # yaml-language-server: $schema=https://aka.ms/winget-manifest.defaultLocale.1.6.0.schema.json
        # Generated by scripts/gen_package_manifests.py — do not edit by hand.
        PackageIdentifier: Tessera.Tessera
        PackageVersion: {version}
        PackageLocale: en-US
        Publisher: Tessera
        PublisherUrl: https://github.com/{repo}
        PublisherSupportUrl: https://github.com/{repo}/issues
        PackageName: Tessera
        PackageUrl: https://github.com/{repo}
        License: MIT
        LicenseUrl: https://github.com/{repo}/blob/main/LICENSE
        Copyright: Copyright (c) 2026 Tessera contributors
        ShortDescription: Explore and query multi-gigabyte CSV, TSV and JSONL files without loading them into memory.
        Description: >-
          Tessera opens CSV, TSV and JSONL files of any size instantly by indexing record
          offsets instead of parsing the whole file, then lets you browse, filter, sort,
          profile and run SQL-style queries over them from the terminal. It is a single
          static executable with no runtime, no network access and no account. Opening a
          1.1 GB, 10-million-row file and answering a grouped query takes a few seconds and
          a few megabytes of memory.
        Moniker: tessera
        Tags:
          - csv
          - tsv
          - jsonl
          - data
          - cli
          - terminal
          - sql
          - explorer
          - large-files
        ReleaseNotesUrl: https://github.com/{repo}/releases/tag/v{version}
        Documentations:
          - DocumentLabel: Documentation
            DocumentUrl: https://github.com/{repo}/tree/main/docs
        ManifestType: defaultLocale
        ManifestVersion: 1.6.0
        """)


def winget_installer_manifest(version: str, repo: str, sha256: str, portable_sha: str | None) -> str:
    # The release ships both a bare .exe and a zip of it; winget wants either a
    # single installer or a zip with a nested portable. Prefer the zip when it is
    # available because winget verifies one download, and fall back to the bare
    # executable otherwise.
    if portable_sha is not None:
        installer = dedent(f"""\
              - Architecture: x64
                InstallerUrl: https://github.com/{repo}/releases/download/v{version}/tessera-windows-x86_64.zip
                InstallerSha256: {sha256}
                InstallerType: zip
                NestedInstallerType: portable
                NestedInstallerFiles:
                  - RelativeFilePath: tessera.exe
                    PortableCommandAlias: tessera
            """)
    else:
        installer = dedent(f"""\
              - Architecture: x64
                InstallerUrl: https://github.com/{repo}/releases/download/v{version}/tessera.exe
                InstallerSha256: {sha256}
                InstallerType: portable
                Commands:
                  - tessera
            """)
    return dedent(f"""\
        # yaml-language-server: $schema=https://aka.ms/winget-manifest.installer.1.6.0.schema.json
        # Generated by scripts/gen_package_manifests.py — do not edit by hand.
        PackageIdentifier: Tessera.Tessera
        PackageVersion: {version}
        Platform:
          - Windows.Desktop
        MinimumOSVersion: 10.0.17763.0
        InstallModes:
          - silent
          - silentWithProgress
        Installers:
        """) + installer + dedent("""\
        ManifestType: installer
        ManifestVersion: 1.6.0
        """)


def scoop_manifest(version: str, repo: str, sha256: str) -> str:
    payload = {
        "version": version,
        "description": "Explore and query multi-gigabyte CSV, TSV and JSONL files without loading them into memory.",
        "homepage": f"https://github.com/{repo}",
        "license": "MIT",
        "architecture": {
            "64bit": {
                "url": f"https://github.com/{repo}/releases/download/v{version}/tessera-windows-x86_64.zip",
                "hash": sha256,
                "extract_dir": "",
            }
        },
        "bin": "tessera.exe",
        "checkver": {"github": f"https://github.com/{repo}"},
        "autoupdate": {
            "architecture": {
                "64bit": {
                    "url": f"https://github.com/{repo}/releases/download/v$version/tessera-windows-x86_64.zip"
                }
            }
        },
    }
    return json.dumps(payload, indent=4) + "\n"


def homebrew_formula(version: str, repo: str, macos_sha: str, linux_sha: str | None) -> str:
    # Homebrew prefers building from source, but a Rust-less C++ project with no
    # dependencies still takes a minute to compile, so the formula installs the
    # release tarball and keeps a `--build-from-source` path out of scope. Intel
    # macOS is omitted rather than pointed at an artifact that does not exist.
    return dedent(f"""\
        # Generated by scripts/gen_package_manifests.py — do not edit by hand.
        class Tessera < Formula
          desc "Explore and query multi-gigabyte CSV, TSV and JSONL files without loading them into memory"
          homepage "https://github.com/{repo}"
          url "https://github.com/{repo}/releases/download/v{version}/tessera-macos-arm64.tar.gz"
          sha256 "{macos_sha}"
          version "{version}"
          license "MIT"

          depends_on arch: :arm64
          depends_on :macos

          def install
            bin.install "tessera"
          end

          test do
            (testpath/"sample.csv").write "id,region,units\\n1,EU,3\\n2,US,7\\n3,EU,11\\n"
            output = shell_output("#{{bin}}/tessera info #{{testpath}}/sample.csv")
            assert_match(/rows\\s+3/, output)
            assert_match(/columns\\s+3/, output)
          end
        end
        """)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--version", required=True, help="release version, without the leading v")
    parser.add_argument("--repo", default=DEFAULT_REPO, help=f"GitHub owner/name (default {DEFAULT_REPO})")
    parser.add_argument("--exe", help="path to the built tessera.exe")
    parser.add_argument("--windows-zip", help="tessera-windows-x86_64.zip")
    parser.add_argument("--linux-tar", help="tessera-linux-x86_64.tar.gz")
    parser.add_argument("--macos-tar", help="tessera-macos-arm64.tar.gz")
    parser.add_argument("--out", default="packaging", help="output root (default packaging)")
    args = parser.parse_args()

    print(f"▸ manifests for v{args.version} ({args.repo})")
    missing: list[str] = []

    if args.windows_zip and os.path.exists(args.windows_zip):
        zip_sha = sha256_of(args.windows_zip)
        write(f"{args.out}/scoop/tessera.json", scoop_manifest(args.version, args.repo, zip_sha))
        write(f"{args.out}/winget/Tessera.Tessera.installer.yaml",
              winget_installer_manifest(args.version, args.repo, zip_sha, zip_sha))
    elif args.exe and os.path.exists(args.exe):
        exe_sha = sha256_of(args.exe)
        write(f"{args.out}/winget/Tessera.Tessera.installer.yaml",
              winget_installer_manifest(args.version, args.repo, exe_sha, None))
        missing.append("tessera-windows-x86_64.zip (Scoop manifest skipped; winget uses the bare .exe)")
    else:
        missing.append("dist/tessera.exe or tessera-windows-x86_64.zip (no Windows manifests generated)")

    write(f"{args.out}/winget/Tessera.Tessera.yaml", winget_version_manifest(args.version, args.repo))
    write(f"{args.out}/winget/Tessera.Tessera.locale.en-US.yaml",
          winget_locale_manifest(args.version, args.repo))

    if args.macos_tar and os.path.exists(args.macos_tar):
        write(f"{args.out}/homebrew/tessera.rb",
              homebrew_formula(args.version, args.repo, sha256_of(args.macos_tar),
                               sha256_of(args.linux_tar) if args.linux_tar and os.path.exists(args.linux_tar) else None))
    else:
        missing.append("tessera-macos-arm64.tar.gz (Homebrew formula skipped)")

    print()
    for name in missing:
        print(f"  note: {name}")
    print(dedent(f"""
        Next steps, once the GitHub release for v{args.version} exists:

          winget:  wingetcreate submit --token <PAT> {args.out}/winget
                   (or open a PR against microsoft/winget-pkgs with those three files)
          scoop:   copy {args.out}/scoop/tessera.json into a Scoop bucket repository,
                   or submit it to https://github.com/ScoopInstaller/Extras
          brew:    push {args.out}/homebrew/tessera.rb to a tap, then
                   `brew install <owner>/tessera/tessera`
        """))
    return 0


if __name__ == "__main__":
    sys.exit(main())
